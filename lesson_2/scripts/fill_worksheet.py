ANSWER_BLUE = RGBColor(0x00, 0x4F, 0xA3)


def style_run(run, size=10.5, bold=False, highlight=False):
    run.font.name = "微软雅黑"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = ANSWER_BLUE
    if highlight:
        run.font.highlight_color = WD_COLOR_INDEX.YELLOW


def set_answer(paragraph, text, size=10.5, bold=False, prefix=True):
    paragraph.text = ""
    run = paragraph.add_run(("【参考填写】" if prefix else "") + text)
    style_run(run, size=size, bold=bold)


def set_cell(cell, text, size=8.5):
    cell.text = text
    for paragraph in cell.paragraphs:
        for run in paragraph.runs:
            style_run(run, size=size)


def fill_paragraph_block(doc, indices, lines):
    if len(indices) != len(lines):
        raise ValueError(f"Paragraph block length mismatch: {indices} vs {len(lines)} lines")
    for idx, line in zip(indices, lines):
        set_answer(doc.paragraphs[idx], line)


